// Запрос, который человек копирует из окна и отдаёт агенту. Это единственное, что ΒybAi
// стоит в токенах: агент читает запрос и пишет файл схемы. Навыка и MCP-сервера нет.
import { KINDS, LIMITS } from './spec';

export const MAP_FILE = '.bybai/map.json';

export const MAP_PROMPT = `Составь схему архитектуры этого проекта для ΒybAi и запиши её в файл ${MAP_FILE} (создай папку, если её нет).

Формат — один JSON-объект:
{
  "title": "короткое название системы",
  "groups": [{ "id": "core", "label": "Ядро" }],
  "nodes": [{ "id": "api", "kind": "service", "label": "API", "tech": "FastAPI", "note": "Одно предложение: что делает.", "group": "core", "files": ["src/api/**"], "run": ["pytest"] }],
  "edges": [{ "from": "api", "to": "db", "label": "SQL" }]
}

Правила:
- 6–16 узлов: только то, что нужно, чтобы понять систему. Узел — это компонент, а не файл.
- kind — одно из: ${KINDS.join(', ')}.
- label до ${LIMITS.label} символов, tech до ${LIMITS.tech}, note — одно предложение до ${LIMITS.note} символов, label связи до ${LIMITS.edgeLabel}.
- id — латинские буквы, цифры и дефис; у каждого узла свой.
- files — шаблоны путей от корня проекта (** — любая глубина). Каждый исходный файл относится не более чем к одному узлу. По ним ΒybAi подсвечивает узел, когда ты работаешь с его файлами.
- run — необязательные фрагменты команд, которые относятся к узлу (например, "pytest" у узла тестов).
- edges направлены по вызову или потоку данных, главный путь идёт слева направо.
- groups необязательны: 2–4 границы, например «Клиент», «Сервер», «Внешние сервисы».
- Меняй только этот файл. Схему в ответе не пересказывай: ответь одной строкой.`;

export const fixPrompt = (errors: string[]): string =>
  `В ${MAP_FILE} есть ошибки. Исправь только их, остальное не меняй, ответь одной строкой:\n${errors.map((e) => `- ${e}`).join('\n')}`;
